// Generates dist/ from src/figma.json. Zero dependencies.
//   dist/tokens.css   — CSS custom properties: light on :root, dark under
//                       [data-theme="dark"] and prefers-color-scheme (unless data-theme="light")
//   dist/tailwind.css — a Tailwind 4 @theme block mapping the same variables to utilities
//   dist/index.ts     — typed objects for React Native (and anything else that wants values)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(readFileSync(join(here, 'src/figma.json'), 'utf8'));
const out = join(here, 'dist');
mkdirSync(out, { recursive: true });

const resolve = (v) => (v.startsWith('@') ? src.primitives[v.slice(1)] : v);
const kebab = (s) => s.replace(/[\/.]/g, '-');
const camel = (s) => s.replace(/[-\/](\w)/g, (_, c) => c.toUpperCase());

const light = {}, dark = {};
for (const [name, v] of Object.entries(src.color)) { light[name] = resolve(v.light); dark[name] = resolve(v.dark); }
for (const v of [...Object.values(light), ...Object.values(dark)]) if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/.test(v)) throw new Error('unresolved colour ' + v);

const rgba = (hex, alpha) => { const n = parseInt(hex.slice(1, 7), 16); return `rgba(${n >> 16},${(n >> 8) & 255},${n & 255},${alpha})`; };
const shadowCss = (layers) => layers.map((l) => `${l.x}px ${l.y}px ${l.blur}px ${l.spread}px ${rgba(l.color, l.alpha)}`).join(', ');

// ---------- tokens.css ----------
const colorVars = (set) => Object.entries(set).map(([k, v]) => `  --color-${kebab(k)}: ${v};`).join('\n');
const staticVars = [
  ...Object.entries(src.primitives).map(([k, v]) => `  --primitive-${kebab(k)}: ${v};`),
  ...Object.entries(src.spacing).map(([k, v]) => `  --space-${kebab(k)}: ${v}px;`),
  ...Object.entries(src.radius).map(([k, v]) => `  --radius-${kebab(k)}: ${v}px;`),
  ...Object.entries(src.motion).filter(([k]) => k.startsWith('duration/')).map(([k, v]) => `  --${kebab(k)}: ${v}ms;`),
  `  --scale-press: ${src.motion['scale/press']};`,
  `  --spring-sheet-tension: ${src.motion['spring/sheet-tension']};`,
  `  --spring-sheet-friction: ${src.motion['spring/sheet-friction']};`,
  `  --font-sans: "${src.font.family}", system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;`,
  ...Object.entries(src.text).flatMap(([k, t]) => [
    `  --type-${k}-size: ${t.size}px;`, `  --type-${k}-line: ${t.lineHeight}px;`, `  --type-${k}-weight: ${t.weight};`, `  --type-${k}-tracking: ${t.letterSpacing}px;`,
  ]),
  ...Object.entries(src.elevation).map(([k, l]) => `  --elevation-${k}: ${shadowCss(l)};`),
  `  --focus-ring: ${shadowCss([src.focusRing])};`,
].join('\n');
const darkOverrides = `  /* Dark separates with a hairline, light with a shadow. */\n  --elevation-sm: none;\n  --elevation-md: none;\n  --elevation-lg: none;`;
writeFileSync(join(out, 'tokens.css'), `/* Generated by @zuuchmap/tokens from Figma — do not edit. */
:root {
  color-scheme: light;
${staticVars}
${colorVars(light)}
}
:root[data-theme="dark"], [data-theme="dark"] {
  color-scheme: dark;
${colorVars(dark)}
${darkOverrides}
}
/* A light island inside a dark page (and vice versa) — e.g. the Toast, which always uses the dark palette. */
[data-theme="light"] {
  color-scheme: light;
${colorVars(light)}
${Object.entries(src.elevation).map(([k, l]) => `  --elevation-${k}: ${shadowCss(l)};`).join('\n')}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${colorVars(dark).replace(/^/gm, '  ')}
${darkOverrides.replace(/^/gm, '  ')}
  }
}
`);

// ---------- tailwind.css ----------
// `@theme inline` so utilities reference the live variable (theme switch needs no rebuild).
const tw = [
  ...Object.keys(src.color).map((k) => `  --color-${kebab(k)}: var(--color-${kebab(k)});`),
  ...Object.keys(src.primitives).map((k) => `  --color-primitive-${kebab(k)}: var(--primitive-${kebab(k)});`),
  ...Object.keys(src.spacing).map((k) => `  --spacing-${kebab(k)}: var(--space-${kebab(k)});`),
  ...Object.keys(src.radius).map((k) => `  --radius-${kebab(k)}: var(--radius-${kebab(k)});`),
  ...Object.keys(src.text).map((k) => `  --text-${k}: var(--type-${k}-size);\n  --text-${k}--line-height: var(--type-${k}-line);\n  --text-${k}--font-weight: var(--type-${k}-weight);\n  --text-${k}--letter-spacing: var(--type-${k}-tracking);`),
  ...Object.keys(src.elevation).map((k) => `  --shadow-${k}: var(--elevation-${k});`),
  `  --shadow-focus: var(--focus-ring);`,
  `  --font-sans: var(--font-sans);`,
  ...Object.entries(src.motion).filter(([k]) => k.startsWith('duration/')).map(([k]) => `  --${kebab(k)}: var(--${kebab(k)});`),
].join('\n');
writeFileSync(join(out, 'tailwind.css'), `/* Generated by @zuuchmap/tokens from Figma — do not edit. Import after tokens.css. */
@theme inline {
${tw}
}
`);

// ---------- index.ts ----------
const weightName = { 400: 'Regular', 500: 'Medium', 600: 'SemiBold', 700: 'Bold', 800: 'ExtraBold' };
const obj = (o, map = (v) => v) => '{\n' + Object.entries(o).map(([k, v]) => `  ${JSON.stringify(camel(k))}: ${map(v, k)},`).join('\n') + '\n}';
const sem = (set) => obj(set, (v) => JSON.stringify(v));
// CSS boxShadow, not shadow*/elevation: Android's `elevation` draws a square shadow behind rounded views.
const rnShadow = (layers) => `{ boxShadow: ${JSON.stringify(shadowCss(layers))} }`;
writeFileSync(join(out, 'index.ts'), `// Generated by @zuuchmap/tokens from Figma — do not edit.
export const fontFamily = ${JSON.stringify(src.font.family)};
/** Static font faces bundled for React Native, keyed by weight. */
export const fontFace = ${obj(Object.fromEntries(src.font.weights.map((w) => [String(w), `${src.font.family}-${weightName[w]}`])), (v) => JSON.stringify(v))} as const;
export const primitives = ${sem(src.primitives)} as const;
export const light = ${sem(light)} as const;
export const dark = ${sem(dark)} as const;
export type ColorToken = keyof typeof light;
export type Colors = { readonly [K in ColorToken]: string };
export const spacing = ${obj(src.spacing)} as const;
export const radius = ${obj(src.radius)} as const;
export const motion = ${obj(src.motion)} as const;
export type TypeRole = ${Object.keys(src.text).map((k) => JSON.stringify(camel(k))).join(' | ')};
/** fontSize / lineHeight / letterSpacing in dp; fontFamily names the bundled static face. */
export const type = ${obj(src.text, (t) => `{ fontFamily: ${JSON.stringify(`${src.font.family}-${weightName[t.weight]}`)}, fontWeight: ${JSON.stringify(String(t.weight))} as const, fontSize: ${t.size}, lineHeight: ${t.lineHeight}, letterSpacing: ${t.letterSpacing} }`)} as const;
/** RN boxShadow for light; the dark theme replaces these with a hairline border (border/elevation). */
export const elevation = ${obj(src.elevation, rnShadow)} as const;
export const elevationCss = ${obj(src.elevation, (l) => JSON.stringify(shadowCss(l)))} as const;
export const focusRing = ${JSON.stringify(src.focusRing)} as const;
export const categoryKeys = ${JSON.stringify(Object.keys(src.primitives).filter((k) => k.startsWith('category/')).map((k) => k.slice(9)))} as const;
export type CategoryKey = typeof categoryKeys[number];
/** Fill colour of a category (theme-independent) and its text tone per theme. */
export const categoryColor = (key: string, scheme: 'light' | 'dark'): { fill: string; text: string } => {
  const fill = (primitives as Record<string, string>)['category' + key.charAt(0).toUpperCase() + key.slice(1)];
  const text = ((scheme === 'dark' ? dark : light) as Record<string, string>)['categoryText' + key.charAt(0).toUpperCase() + key.slice(1)];
  return { fill: fill ?? (scheme === 'dark' ? dark.textSecondary : light.textSecondary), text: text ?? (scheme === 'dark' ? dark.textSecondary : light.textSecondary) };
};
`);
console.log(`tokens: ${Object.keys(light).length} colours × 2 themes, ${Object.keys(src.spacing).length} spacing, ${Object.keys(src.radius).length} radius, ${Object.keys(src.text).length} type roles → dist/`);
